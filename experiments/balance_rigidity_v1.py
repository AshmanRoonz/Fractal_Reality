from __future__ import annotations

import math
from fractions import Fraction

import numpy as np


def rational_stations(m: int, b: Fraction) -> tuple[Fraction, ...]:
    """Return the ordered distinct stations for depth m and balance b."""
    values: list[Fraction] = []
    for j in range(m):
        values.extend((Fraction(j), Fraction(j) + b))
    values.append(Fraction(m))
    return tuple(values)


def residue(x: Fraction, length: Fraction) -> Fraction:
    return x - (x // length) * length


def is_closed(m: int, b: Fraction) -> bool:
    length = Fraction(m) + b
    station_set = set(rational_stations(m, b))
    return all(
        residue(x + y, length) in station_set
        for x in station_set
        for y in station_set
    )


def exact_gap_variance(m: int, b: Fraction) -> Fraction:
    gaps = [value for _ in range(m) for value in (b, 1 - b)] + [b]
    mean = sum(gaps, Fraction(0)) / len(gaps)
    return sum((gap - mean) ** 2 for gap in gaps) / len(gaps)


def expected_gap_variance(m: int, b: Fraction) -> Fraction:
    count = 2 * m + 1
    return Fraction(m * (m + 1), count * count) * (2 * b - 1) ** 2


def exact_uniform_errors(m: int, b: Fraction) -> tuple[Fraction, ...]:
    count = 2 * m + 1
    length = Fraction(m) + b
    spacing = length / count
    return tuple(
        station - k * spacing
        for k, station in enumerate(rational_stations(m, b))
    )


def expected_uniform_errors(m: int, b: Fraction) -> tuple[Fraction, ...]:
    count = 2 * m + 1
    delta = b - Fraction(1, 2)
    result: list[Fraction] = []
    for j in range(m):
        result.extend(
            (
                -Fraction(2 * j, count) * delta,
                Fraction(2 * (m - j), count) * delta,
            )
        )
    result.append(-Fraction(2 * m, count) * delta)
    return tuple(result)


def exact_generated_order(m: int, b: Fraction) -> int:
    """Order of the subgroup generated by the visible stations."""
    return m * b.denominator + b.numerator


def exact_sumset_size(m: int, b: Fraction, depth: int) -> int:
    length = Fraction(m) + b
    return len(
        {
            residue(Fraction(value), length)
            for value in range(-depth * m, depth * m + 1)
        }
    )


def rotational_stabilizer_shifts(m: int, b: Fraction) -> tuple[int, ...]:
    gaps = tuple([value for _ in range(m) for value in (b, 1 - b)] + [b])
    count = len(gaps)
    return tuple(
        shift
        for shift in range(count)
        if all(gaps[index] == gaps[(index + shift) % count] for index in range(count))
    )


def float_stations(m: int, b: float) -> np.ndarray:
    values: list[float] = []
    for j in range(m):
        values.extend((float(j), j + b))
    values.append(float(m))
    return np.asarray(values)


def fourier_matrix(m: int, b: float) -> np.ndarray:
    count = 2 * m + 1
    length = m + b
    stations = float_stations(m, b)
    modes = np.arange(count)
    return np.exp(2j * np.pi * np.outer(stations / length, modes)) / math.sqrt(
        count
    )


def dirichlet_moment(m: int, b: float, r: int) -> float:
    """Return the normalized r-th circular moment in closed form."""
    if r == 0:
        return 1.0
    count = 2 * m + 1
    length = m + b
    return math.sin(count * math.pi * r / length) / (
        count * math.sin(math.pi * r / length)
    )


def exact_audit() -> tuple[int, int]:
    balances = sorted(
        {
            Fraction(numerator, denominator)
            for denominator in range(2, 51)
            for numerator in range(1, denominator)
        }
    )
    depths = range(1, 13)

    for m in depths:
        closed_values: list[Fraction] = []
        for b in balances:
            if is_closed(m, b):
                closed_values.append(b)
            assert exact_gap_variance(m, b) == expected_gap_variance(m, b)
            assert exact_uniform_errors(m, b) == expected_uniform_errors(m, b)

            length = Fraction(m) + b
            order = exact_generated_order(m, b)
            assert residue(Fraction(order), length) == 0
            assert all(
                residue(Fraction(value), length) != 0
                for value in range(1, order)
            )
            if b == Fraction(1, 2):
                assert order == 2 * m + 1
                assert rotational_stabilizer_shifts(m, b) == tuple(
                    range(2 * m + 1)
                )
            else:
                assert order > 2 * m + 1
                assert rotational_stabilizer_shifts(m, b) == (0,)

            saturation_depth = math.ceil((order - 1) / (2 * m))
            for depth in range(1, min(5, saturation_depth + 1) + 1):
                assert exact_sumset_size(m, b, depth) == min(
                    order, 2 * depth * m + 1
                )
            assert exact_sumset_size(m, b, saturation_depth) == order
            if saturation_depth > 1:
                assert exact_sumset_size(m, b, saturation_depth - 1) < order
        assert closed_values == [Fraction(1, 2)]

    return len(balances), len(tuple(depths))


def numerical_audit() -> tuple[int, int]:
    grid = np.linspace(0.05, 0.95, 181)
    depths = range(1, 13)

    for m in depths:
        conditions: list[float] = []
        for b in grid:
            matrix = fourier_matrix(m, float(b))
            gram = matrix.conj().T @ matrix
            count = 2 * m + 1

            for p in range(count):
                for q in range(count):
                    expected = dirichlet_moment(m, float(b), q - p)
                    assert abs(gram[p, q] - expected) < 2e-12

            direct_moment = np.mean(
                np.exp(2j * np.pi * float_stations(m, float(b)) / (m + b))
            )
            assert abs(direct_moment - dirichlet_moment(m, float(b), 1)) < 2e-12
            assert abs(direct_moment.imag) < 2e-12
            if abs(b - 0.5) < 1e-15:
                assert abs(direct_moment.real) < 2e-12
            else:
                assert direct_moment.real * (0.5 - b) > 0
            assert np.linalg.matrix_rank(matrix, tol=1e-11) == count
            conditions.append(float(np.linalg.cond(matrix)))

        best = int(np.argmin(conditions))
        assert abs(grid[best] - 0.5) < 1e-15
        assert abs(conditions[best] - 1.0) < 2e-12
        assert all(
            condition > 1.0 + 1e-10
            for index, condition in enumerate(conditions)
            if index != best
        )

    return len(grid), len(tuple(depths))


def print_framework_table() -> None:
    print("\nFramework case: m = 3, N = 7")
    print("b       cond(F_b)    max |G-I|   |first moment|   gap variance")
    for b in (0.10, 0.20, 0.30, 0.40, 0.45, 0.49, 0.50, 0.51, 0.55, 0.60, 0.70, 0.80, 0.90):
        matrix = fourier_matrix(3, b)
        gram = matrix.conj().T @ matrix
        condition = np.linalg.cond(matrix)
        off_diagonal = np.max(np.abs(gram - np.eye(7)))
        first_moment = abs(dirichlet_moment(3, b, 1))
        variance = 12.0 / 49.0 * (2.0 * b - 1.0) ** 2
        print(
            f"{b:0.2f}    {condition:11.6f}   {off_diagonal:11.6f}"
            f"   {first_moment:14.6f}   {variance:12.6f}"
        )


def main() -> None:
    rational_count, exact_depth_count = exact_audit()
    grid_count, numerical_depth_count = numerical_audit()

    print("Odd-cycle balance-rigidity verification")
    print(f"exact rational balances per depth: {rational_count}")
    print(f"exact depths checked: 1 through {exact_depth_count}")
    print(f"numerical balance grid per depth: {grid_count}")
    print(f"numerical depths checked: 1 through {numerical_depth_count}")
    print("unique closed value on every exact scan: b = 1/2")
    print("gap-variance identity: exact")
    print("anchored uniform-error identity: exact")
    print("rational closure-order identity: exact")
    print("rotational-stabilizer identity: exact")
