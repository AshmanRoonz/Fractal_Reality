def sinkhorn(w, iters=200, tol=1e-11):
    """G.sinkhorn with the same arithmetic, sweeping sparsely once the matrix is mostly zeros. Speed only."""
    n = len(w)
    M = csr_matrix(w) if np.count_nonzero(w) < 0.1 * n * n else w
    d = np.ones(n)
    live = w.sum(1) > 0
    for _ in range(iters):
        s = M @ d
        d[live] = np.sqrt(d[live] / np.maximum(s[live], 1e-280))
        d = np.minimum(d, 1e100)
        if np.max(np.abs((d * (M @ d) - 1)[live]), initial=0.0) < tol:
            break
    return np.nan_to_num(w * np.outer(d, d), nan=0.0, posinf=0.0)


