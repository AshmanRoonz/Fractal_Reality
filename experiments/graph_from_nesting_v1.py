def e_cycle(n):
    return n, [(i, (i + 1) % n) for i in range(n)]


def e_complete(n):
    return n, [(i, j) for i in range(n) for j in range(i + 1, n)]


def e_cube(d):
    n = 2 ** d
    return n, [(i, i ^ (1 << l)) for i in range(n) for l in range(d) if i < i ^ (1 << l)]


def e_kaa(a):
    return 2 * a, [(i, a + j) for i in range(a) for j in range(a)]


def e_prism():
    return 6, [(0, 1), (1, 2), (2, 0), (3, 4), (4, 5), (5, 3), (0, 3), (1, 4), (2, 5)]


def e_petersen():
    return 10, [(i, (i + 1) % 5) for i in range(5)] + [(5 + i, 5 + (i + 2) % 5) for i in range(5)] + [(i, 5 + i) for i in range(5)]


def sides(n, edges):
    nb = defaultdict(list)
    for i, j in edges:
        nb[i].append(j)
        nb[j].append(i)
    col = {0: 0}
    stack = [0]
    while stack:
        u = stack.pop()
        for v in nb[u]:
            if v not in col:
                col[v] = 1 - col[u]
                stack.append(v)
            elif col[v] == col[u]:
                return None
    return [col[i] for i in range(n)]


def max_share(n, edges, doors, lo=1e-3):
    m, d = len(edges), len(doors)
    A = np.zeros((n, m + d))
    for k, (i, j) in enumerate(edges):
        A[i, k] = A[j, k] = 1
    for k, i in enumerate(doors):
        A[i, m + k] = 1
    c = np.r_[np.zeros(m), -np.ones(d)]
    res = linprog(c, A_eq=A, b_eq=np.ones(n), bounds=[(lo, None)] * m + [(0, None)] * d, method="highs")
    return float(-res.fun) if res.status == 0 else None


