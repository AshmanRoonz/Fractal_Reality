def fixed_point(job):
    b, L, gamma, beta, seed = job
    S = ((np.arange(1, 2 ** L)[:, None] >> np.arange(L)) & 1).astype(float)
    mult = (b - 1.0) ** S.sum(1)
    n = float(b) ** L
    # Equal level weights are a fixed point by symmetry, so three other starts. 0: geometric. 7: large noise. 11: equal plus tiny noise.
    if seed == 0:
        w = 0.5 ** np.arange(L)
    elif seed == 7:
        w = np.exp(np.random.default_rng(seed).normal(0, 1, L))
    else:
        w = np.exp(1e-3 * np.random.default_rng(seed).normal(0, 1, L))
    w /= (b - 1) * w.sum()
    floor = 1e-80
    collapsed = False
    it = 0
    for it in range(1, 6001):
        lam = b * (S @ w)
        e = (S.T @ (mult * lam ** (-gamma))) * b * w / (n * (b - 1) / 2)
        logw = (1 - ETA) * np.log(w) + ETA * beta * np.log(np.maximum(e, 1e-300))
        logw -= logw.max()
        new = np.exp(logw)
        new /= (b - 1) * new.sum()
        if new.min() < floor:
            new = np.maximum(new, floor)
            collapsed = True
            w = new / ((b - 1) * new.sum())
            break
        if np.abs(np.log(new / w)).max() < 1e-10:
            w = new
            break
        w = new
    w = np.sort(w)[::-1]
    lo, hi = L // 4, (3 * L) // 4
    ratios = w[lo + 1:hi + 1] / w[lo:hi]
    r = float(np.exp(np.log(ratios).mean()))
    lam = b * (S @ w)
    order = np.argsort(lam)
    cum = np.cumsum(mult[order]) / n
    grid = np.geomspace(b * w[hi], b * w[lo], 60)
    N = cum[np.minimum(np.searchsorted(lam[order], grid), len(cum) - 1)]
    ds = float(2 * np.polyfit(np.log(grid), np.log(N), 1)[0])
    foster = float(((S.T @ (mult * lam ** (-gamma))) * b * w).sum()) if gamma == 1 else None
    return dict(b=b, L=L, gamma=gamma, beta=beta, seed=seed, r=r, r_lo=float(ratios.min()), r_hi=float(ratios.max()), ds=ds, ds_from_r=float(2 * np.log(b) / max(np.log(1 / r), 1e-12)),
                collapsed=collapsed or r < 1e-3, iters=it, foster=foster, foster_target=n - 1, w=w.tolist())


