def grow_job(job):
    mode, gamma, beta, t0, r, beta0, noise, n, seed, T = job
    rng = np.random.default_rng([n, seed, int(gamma * 100), int(beta * 100), int(t0 * 100), int(r * 100), int(beta0 * 100), int(noise * 1000), mode == "free"])
    W = np.zeros((n, n))
    blocks = [np.array([i]) for i in range(n)]
    J = -np.ones((n, n), int)
    history = []
    level = 0
    top_conv = False
    t_start = time.time()
    while len(blocks) > 1:
        Q, groups = pair_up(len(blocks), beta0, noise, rng)
        if len(groups) == len(blocks):
            m = len(blocks)
            Q = (np.ones((m, m)) - np.eye(m)) / max(m - 1, 1)
            groups = [list(range(m))]
        newblocks = []
        for g in groups:
            if len(g) == 1:
                newblocks.append(blocks[g[0]])
                continue
            U = np.concatenate([blocks[a] for a in g])
            sub = W[np.ix_(U, U)]
            rel = np.zeros_like(sub)
            offs = {}
            pos = 0
            for a in g:
                offs[a] = np.arange(pos, pos + len(blocks[a]))
                pos += len(blocks[a])
            for x in range(len(g)):
                for y in range(x + 1, len(g)):
                    a, b = g[x], g[y]
                    if Q[a, b] > SUPPORT:
                        A_, B_ = offs[a], offs[b]
                        vals = Q[a, b] / np.sqrt(len(A_) * len(B_)) * np.exp(0.05 * rng.normal(size=(len(A_), len(B_))))
                        rel[np.ix_(A_, B_)] = vals
                        rel[np.ix_(B_, A_)] = vals.T
                        J[np.ix_(U[A_], U[B_])] = level
                        J[np.ix_(U[B_], U[A_])] = level
            if mode == "free":
                t = t0
            else:
                t = r ** level / sum(r ** m_ for m_ in range(level + 1))
            mix = (1 - t) * sub + t * rel if sub.any() else rel
            mix = G.sinkhorn(mix)
            mix[mix < 1e-12] = 0
            mix = (mix + mix.T) / 2
            newmask = rel > 0
            conv = False
            for it in range(1, T + 1):
                if mode == "free":
                    new = G.step(mix, "site", gamma, beta)
                else:
                    e = G.edge_energy(mix, gamma)
                    m_ = newmask & (mix > 0)
                    new = mix.copy()
                    if m_.any():
                        share = mix[m_].sum()
                        new[m_] = np.exp((1 - ETA) * np.log(mix[m_]) + ETA * beta * np.log(np.maximum(e[m_], 1e-300)))
                        new[m_] *= share / new[m_].sum()
                    new = G.sinkhorn(new)
                    new[new < 1e-12] = 0
                    new = (new + new.T) / 2
                if it % 10 == 0:
                    o = (new > SUPPORT) | (mix > SUPPORT)
                    if o.any() and (np.abs(new[o] - mix[o]) / np.maximum(mix[o], SUPPORT)).max() < 1e-6:
                        mix = new
                        conv = True
                        break
                mix = new
            W[np.ix_(U, U)] = mix
            newblocks.append(U)
            top_conv = conv
        blocks = newblocks
        history.append([b.copy() for b in blocks])
        level += 1
    W = (W + W.T) / 2
    W[W < SUPPORT] = 0
    out = geom(W, seed, do_plane=n <= 512)
    s = W.sum(1)
    out["row_err"] = float(np.abs(s - 1).max())
    table = []
    for l, bl in enumerate(history[:-1]):
        sizes, doors, share, autonomy = [], [], [], []
        for B in bl:
            if len(B) < 2:
                continue
            mask = np.ones(n, bool)
            mask[B] = False
            o = W[np.ix_(B, np.flatnonzero(mask))].sum(1)
            sizes.append(len(B))
            doors.append(int((o > SUPPORT).sum()))
            share.append(float(o.mean()))
            if len(B) <= 300:
                autonomy.append(WP.autonomy_part(W, s, list(B)))
        table.append(dict(level=l, size=float(np.mean(sizes)), doors=float(np.mean(doors)), share=float(np.mean(share)), A=float(np.mean(autonomy)) if autonomy else float("nan"),
                          tau=float(W[J == l].sum() / n), edges_per_site=float((W[J == l] > 0).sum() / n)))
    out.update(mode=mode, gamma=gamma, beta=beta, t0=t0, r=r, beta0=beta0, noise=noise, seed=seed, T=T, top_conv=top_conv, levels_built=level, table=table, secs=time.time() - t_start)
    return out


def baseline_job(job):
    gamma, beta, n, seed, T = job
    rng = np.random.default_rng([n, seed, int(gamma * 100), int(beta * 100), 77])
    w = G.normalize(G.start(n, 0.05, rng), "site")
    conv = False
    it = 0
    for it in range(1, T + 1):
        new = G.step(w, "site", gamma, beta)
        if it % 10 == 0:
            o = (new > SUPPORT) | (w > SUPPORT)
            if (np.abs(new[o] - w[o]) / np.maximum(w[o], SUPPORT)).max() < 1e-6:
                w = new
                conv = True
                break
        w = new
    w[w < SUPPORT] = 0
    out = geom(w, seed, do_plane=n <= 512)
    out.update(mode="baseline", gamma=gamma, beta=beta, seed=seed, top_conv=conv)
    return out


def holdout(rows, sizes):
    """Fit diameter against largest-piece size on n <= 256, predict above."""
    by = {n: [x for x in rows if x["n"] == n and "diameter" in x] for n in sizes}
    pts = [(np.mean([x["largest"] for x in by[n]]), np.mean([x["diameter"] for x in by[n]])) for n in sizes if n <= 256 and by[n]]
    if len(pts) < 3:
        return None
    pts = np.array(pts)
    a, b = np.polyfit(np.log(pts[:, 0]), np.log(pts[:, 1]), 1)
    c, d = np.polyfit(np.log(pts[:, 0]), pts[:, 1], 1)
    out = dict(exponent=float(a), tests=[])
    for n in sizes:
        if n > 256 and by[n]:
            size = np.mean([x["largest"] for x in by[n]])
            act = np.mean([x["diameter"] for x in by[n]])
            out["tests"].append(dict(n=n, largest=float(size), actual=float(act), power=float(np.exp(b) * size ** a), log=float(c * np.log(size) + d)))
    return out


