def product(b, L, r, pattern="complete"):
    """Product of K_b (or C_b), level l per-site share proportional to r^l, row sums 1."""
    n = b ** L
    tau = r ** np.arange(L)
    tau = tau / tau.sum()
    W = np.zeros((n, n))
    p = b ** np.arange(L)
    for l in range(L):
        for i in range(n):
            d = (i // p[l]) % b
            base = i - d * p[l]
            if pattern == "complete":
                for x in range(b):
                    if x != d:
                        W[i, base + x * p[l]] = tau[l] / (b - 1)
            else:
                for x in ((d + 1) % b, (d - 1) % b):
                    W[i, base + x * p[l]] += tau[l] / 2 if b > 2 else tau[l]
    return W


def spread_family(b, L, r):
    """Dyson-style: level l share spread evenly over all partners at that level."""
    n = b ** L
    tau = r ** np.arange(L)
    tau = tau / tau.sum()
    W = np.zeros((n, n))
    for l in range(L):
        size = b ** (l + 1)
        below = b ** l
        count = size - below
        for start_ in range(0, n, size):
            idx = np.arange(start_, start_ + size)
            grp = (idx - start_) // below
            M = (grp[:, None] != grp[None, :]).astype(float)
            W[np.ix_(idx, idx)] += M * tau[l] / count
    return W


def ds_weyl(lam):
    lam = np.sort(lam)
    lam = lam[lam > 1e-12]
    n = len(lam)
    k = np.unique(np.geomspace(3, max(n // 4, 4), 40).astype(int))
    k = k[k < n]
    if len(k) < 3:
        return float("nan")
    return float(2 * np.polyfit(np.log(lam[k]), np.log(k + 1.0), 1)[0])


def metric_tests(A, rng, nsrc=40):
    n = len(A)
    src = rng.choice(n, min(nsrc, n), replace=False)
    Lg = np.zeros_like(A)
    on = A > 0
    Lg[on] = 1 / A[on]
    D = shortest_path(csr_matrix(Lg), directed=False, indices=src)
    vals = []
    for a in range(len(src)):
        for b in range(a + 1, len(src)):
            dxy = D[a, src[b]]
            if dxy > 0 and np.isfinite(dxy):
                vals.append((dxy, np.maximum(D[a], D[b]).min() / dxy))
    if not vals:
        return dict(midpoint=float("nan"), d_metric=float("nan"))
    vals = np.array(vals)
    mid = float(vals[vals[:, 0] >= np.median(vals[:, 0]), 1].mean())
    pos = D[np.isfinite(D) & (D > 0)]
    rho = np.geomspace(pos.min(), pos.max(), 40)
    V = np.array([(D <= x).sum(1).mean() for x in rho])
    keep = (V >= 4) & (V <= n / 4)
    dm = float(np.polyfit(np.log(rho[keep]), np.log(V[keep]), 1)[0]) if keep.sum() >= 4 else float("nan")
    return dict(midpoint=mid, d_metric=dm)


def geom(W, seed, do_plane):
    """Geometry of the largest piece."""
    A = W * (W > SUPPORT)
    A = (A + A.T) / 2
    np.fill_diagonal(A, 0)
    rng = np.random.default_rng(seed + 12345)
    ncomp, lab = connected_components(csr_matrix(A), directed=False)
    big = np.flatnonzero(lab == np.argmax(np.bincount(lab)))
    out = dict(n=len(W), components=int(ncomp), largest=int(len(big)), connected=bool(ncomp == 1))
    deg = (A > 0).sum(1)
    out["mean_degree"] = float(deg.mean())
    out["max_degree"] = int(deg.max())
    out["ring"] = bool(ncomp == 1 and np.all(deg == 2))
    if len(big) < 8:
        return out
    B = A[np.ix_(big, big)]
    fm = G.family_metrics(B, seed=seed)
    out.update({k: fm[k] for k in ("diameter", "lambda2", "conductance", "d_growth", "d_spectral", "interior")})
    S = (B > 0).astype(int)
    d = S.sum(1)
    trip = (d * (d - 1) / 2).sum()
    out["clustering"] = float(np.trace(S @ S @ S) / 2 / trip) if trip and len(B) <= 2100 else 0.0
    s = B.sum(1)
    K = np.eye(len(B)) - B / np.sqrt(np.outer(s, s))
    out["ds_weyl"] = ds_weyl(np.linalg.eigvalsh(K))
    out.update(metric_tests(B, rng))
    if do_plane:
        lv, _ = WP.plane(B)
        acc = [x for x in lv if x.get("level")]
        out["levels"] = len(acc)
        out["level_ac"] = [(int(x["k"]), float(x["a"]), float(x["c"])) for x in acc]
        out["best_ac"] = (float(lv[0]["a"]), float(lv[0]["c"]))
    return out


# ---------- Part: capacity ----------
def capacity_job(job):
    b, pattern, L, level, r = job
    W = product(b, L, r, pattern)
    size = b ** (level + 1)
    S = list(range(size))
    block = W[np.ix_(S, S)]
    s = W.sum(1)
    A = WP.autonomy_part(W, s, S)
    rm, re = WP.slow_mode_rates(W, S, block)
    return dict(b=b, pattern=pattern, r=r, A=float(A), r_mix=float(rm), r_esc=float(re))


