def pair_up(m, beta0, noise, rng, maxit=300):
    """gamma=0 site-budget rule among m sites. Returns the pattern Q and the groups. e_ij = 2 w_ij, so f = (2w)^beta0."""
    if m == 1:
        return np.zeros((1, 1)), [[0]]
    if m == 2:
        return np.array([[0.0, 1.0], [1.0, 0.0]]), [[0, 1]]
    if m == 3:
        return (np.ones((3, 3)) - np.eye(3)) / 2, [[0, 1, 2]]
    w = G.normalize(G.start(m, noise, rng), "site")
    last = None
    stable = 0
    for it in range(1, maxit + 1):
        new = np.zeros_like(w)
        on = w > 0
        new[on] = w[on] ** (1 - ETA + ETA * beta0)
        new = G.sinkhorn(new)
        new[new < 1e-12] = 0
        w = (new + new.T) / 2
        if it % 5 == 0:
            A = w > SUPPORT
            key = A.sum()
            if A.sum(1).max() <= 2 and key == last:
                stable += 1
                if stable >= 3:
                    break
            else:
                stable = 0
            last = key
    Q = w * (w > SUPPORT)
    Q = G.sinkhorn(Q)
    Q[Q < SUPPORT] = 0
    Q = (Q + Q.T) / 2
    _, lab = connected_components(csr_matrix(Q), directed=False)
    groups = [list(np.flatnonzero(lab == l)) for l in np.unique(lab)]
    return Q, groups


def blocks_job(job):
    n, beta0, noise, seed = job
    rng = np.random.default_rng([n, int(beta0 * 100), int(noise * 1000), seed])
    m = n
    rows = []
    while m > 1:
        Q, groups = pair_up(m, beta0, noise, rng)
        sizes = [len(g) for g in groups]
        rows.append(dict(m=m, kinds=dict(Counter(sizes)), mean=float(np.mean(sizes))))
        if len(groups) == m:
            break
        m = len(groups)
    return dict(n=n, beta0=beta0, noise=noise, seed=seed, rows=rows)


