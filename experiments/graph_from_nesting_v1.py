def run_jobs(pool, fn, jobs, outdir, tag, ordered=False):
    """Run jobs, saving each result as it arrives and reporting progress, so a long part can be watched and a stopped one keeps its work."""
    t = time.time()
    res = []
    every = max(1, len(jobs) // 20)
    it = pool.imap(fn, jobs, chunksize=1) if ordered else pool.imap_unordered(fn, jobs, chunksize=1)
    with open(os.path.join(outdir, tag + ".jsonl"), "w") as fh:
        for x in it:
            res.append(x)
            fh.write(json.dumps(x, default=float) + "\n")
            fh.flush()
            if len(res) % every == 0 or len(res) == len(jobs):
                print(f"[{tag}] {len(res)}/{len(jobs)} jobs, {time.time() - t:.0f}s", flush=True)
    return res


