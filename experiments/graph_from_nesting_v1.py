# ---------- Part: static ----------
def static_job(job):
    kind, b, L, r = job
    if kind == "ring":
        W = G.adj_ring(b)
        W = W / W.sum(1, keepdims=True)
    elif kind == "torus":
        W = G.adj_torus(b, L)
        W = W / W.sum(1, keepdims=True)
    elif kind == "gasket":
        W = G.adj_gasket(L)
        W = WP.symmetrize(W, 0) if False else W
    elif kind == "product":
        W = product(b, L, r)
    else:
        W = spread_family(b, L, r)
    out = geom(W, 1, do_plane=len(W) <= 800 and kind in ("product", "spread"))
    out.update(kind=kind, b=b, L=L, r=r)
    return out


