def dense_job(job):
    b, L, gamma, beta, seed = job
    fp = fixed_point((b, 14 if b == 2 else 14, gamma, beta, 0))
    ww = np.array(fp["w"])
    r = fp["r"]
    W = product(b, L, r)
    n = len(W)
    rng = np.random.default_rng([b, L, seed])
    g = rng.normal(0, 1, (n, n))
    g = (g + g.T) / np.sqrt(2)
    on = W > 0
    W[on] = W[on] * np.exp(0.02 * g[on])
    W = G.sinkhorn(W)
    W = (W + W.T) / 2
    p = b ** np.arange(L)
    lev = np.full((n, n), -1)
    for l in range(L):
        for i in range(n):
            d = (i // p[l]) % b
            base = i - d * p[l]
            for x in range(b):
                if x != d:
                    lev[i, base + x * p[l]] = l
    def spread(w):
        v = []
        for l in range(L):
            m = (lev == l) & (w > 0)
            if m.sum() > 1:
                v.append(np.log(w[m]).std())
        return float(np.mean(v))
    s0 = spread(W)
    deg0 = float((W > SUPPORT).sum(1).mean())
    conv = False
    it = 0
    for it in range(1, 801):
        new = G.step(W, "site", gamma, beta)
        if it % 10 == 0:
            o = (new > SUPPORT) | (W > SUPPORT)
            if (np.abs(new[o] - W[o]) / np.maximum(W[o], SUPPORT)).max() < 1e-7:
                W = new
                conv = True
                break
        W = new
    out = geom(W, seed, do_plane=False)
    out.update(b=b, L=L, gamma=gamma, beta=beta, seed=seed, spread0=s0, spread1=spread(W * (W > SUPPORT)), degree0=deg0, iters=it, converged=conv,
               shares=[float(W[lev == l].sum() / n) for l in range(L)])
    return out


